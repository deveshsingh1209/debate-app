#!/usr/bin/env node
/**
 * Production dependency licence audit, offline.
 *
 *   node scripts/release/licenses.mjs           # print the table, exit 1 on anything to review
 *   node scripts/release/licenses.mjs --write   # also regenerate THIRD_PARTY_NOTICES.md
 *
 * The package list comes from `npm ls --omit=dev --all` (the installed tree,
 * no network); each licence from the package's own package.json and its
 * LICENSE file. Anything not in the allowed set is flagged. Run `npm ci`
 * first so node_modules matches the lockfile.
 */
import { execFileSync } from 'node:child_process';
import fs from 'node:fs';
import path from 'node:path';

const ALLOWED = /^(MIT|ISC|BSD-2-Clause|BSD-3-Clause|0BSD|Apache-2\.0|MPL-2\.0|CC0-1\.0|OFL-1\.1|BlueOak-1\.0\.0|Unlicense|CC-BY-4\.0|Python-2\.0)$/;
/** Reviewed by hand; the reason is printed next to the package. */
const REVIEWED = {
  '@anthropic-ai/claude-agent-sdk':
    'Proprietary (Anthropic, "all rights reserved", use under Anthropic\'s legal terms). Not redistributed by this project: npm installs it on the user\'s machine from the npm registry. Keep node_modules out of every release artefact.',
};
/** libvips (LGPL-3.0-or-later): an optional, prebuilt, dynamically loaded image library the Claude Agent SDK pulls in per platform. */
const REVIEWED_PREFIX = [[/^@img\/sharp-libvips-/,
  'LGPL-3.0-or-later. A prebuilt shared library that npm installs per platform as an optional dependency of the Claude Agent SDK (through sharp). It is loaded dynamically, not modified and not shipped in this repository or its zip, so the LGPL asks nothing of this project; anyone who redistributes node_modules must offer its source (github.com/lovell/sharp-libvips).']];
const reviewOf = (name) => REVIEWED[name] ?? REVIEWED_PREFIX.find(([re]) => re.test(name))?.[1];

const root = process.cwd();
const json = JSON.parse(execFileSync('npm', ['ls', '--omit=dev', '--all', '--json', '--long'], { encoding: 'utf8', maxBuffer: 1 << 28, shell: process.platform === 'win32' }));

const pkgs = new Map();
(function walk(deps) {
  for (const [name, d] of Object.entries(deps ?? {})) {
    // This repository's own workspaces (server, web) are not third-party: walk through them.
    if (!d.path || !d.version || !d.path.split(path.sep).includes('node_modules')) { walk(d.dependencies); continue; }
    const key = `${name}@${d.version}`;
    if (!pkgs.has(key)) pkgs.set(key, { name, version: d.version, dir: d.path });
    walk(d.dependencies);
  }
})(json.dependencies);

function licenceOf(dir) {
  const pj = JSON.parse(fs.readFileSync(path.join(dir, 'package.json'), 'utf8'));
  let id = typeof pj.license === 'string' ? pj.license : pj.license?.type ?? (Array.isArray(pj.licenses) ? pj.licenses.map((l) => l.type ?? l).join(' OR ') : 'UNKNOWN');
  const file = fs.readdirSync(dir).find((f) => /^(licen[sc]e|copying)(\.|$|-)/i.test(f));
  const text = file ? fs.readFileSync(path.join(dir, file), 'utf8').trim() : '';
  const repo = typeof pj.repository === 'string' ? pj.repository : pj.repository?.url ?? '';
  return { id, text, file, repo: repo.replace(/^git\+/, '').replace(/\.git$/, ''), author: typeof pj.author === 'string' ? pj.author : pj.author?.name ?? '' };
}

/** An SPDX expression passes when every OR branch has an allowed option, i.e. some branch is fully allowed. */
const allowed = (id) => id.replace(/[()]/g, '').split(/\s+OR\s+/).some((alt) => alt.split(/\s+AND\s+/).every((p) => ALLOWED.test(p.trim())));

const rows = [...pkgs.values()].sort((a, b) => a.name.localeCompare(b.name)).map((p) => ({ ...p, ...licenceOf(p.dir) }));
const flagged = rows.filter((r) => !allowed(r.id));
const counts = {};
for (const r of rows) counts[r.id] = (counts[r.id] ?? 0) + 1;

console.log(`${rows.length} production packages`);
for (const [id, n] of Object.entries(counts).sort((a, b) => b[1] - a[1])) console.log(`  ${String(n).padStart(3)}  ${id}`);
for (const r of flagged) console.log(`\nREVIEW ${r.name}@${r.version}: ${r.id}\n  ${reviewOf(r.name) ?? 'NOT REVIEWED'}`);

if (process.argv.includes('--write')) {
  const fonts = rows.filter((r) => r.name.startsWith('@fontsource'));
  const out = [];
  out.push('# Third-party notices', '');
  out.push('The Debate App is MIT licensed (see [LICENSE](LICENSE)). It depends on the packages below, which npm downloads from the npm registry when you install or start the app. This repository and its release zip contain none of their code, with one exception: the fonts below are bundled into the built web app and inlined into reports, so their licence travels with every build.', '');
  out.push('Generated by `node scripts/release/licenses.mjs --write` from the installed production tree (`npm ls --omit=dev --all`). Development-only tools (TypeScript, Vite, esbuild, tsx, concurrently) are not shipped and are not listed. Packages named for a platform (`-darwin-arm64` and the like) are the ones npm picked for the machine this ran on; on Windows or Linux npm installs that platform\'s twin, under the same licence.', '');
  out.push('## Fonts (SIL Open Font License 1.1)', '');
  out.push('Self-hosted through the Fontsource packages; no font is fetched from the internet. The OFL lets the fonts be bundled and redistributed with software, provided the copyright notice and licence go with them and the fonts are not sold on their own.', '');
  out.push('| Font | Package | Copyright |', '|---|---|---|');
  // The Fontsource copy of Source Serif's licence names no holder; this is the upstream notice.
  const UPSTREAM = { 'source-serif-4': 'Copyright 2014-2021 Adobe (http://www.adobe.com/), with Reserved Font Name "Source"' };
  for (const f of fonts) {
    const short = f.name.replace(/^@fontsource(-variable)?\//, '');
    const copy = UPSTREAM[short] ?? f.text.split('\n').find((l) => /^Copyright\b.*\d{4}/.test(l.trim()))?.split(/\s\S+\.ttf:/)[0].trim() ?? '(see the licence text below)';
    out.push(`| ${f.name.replace(/^@fontsource(-variable)?\//, '')} | ${f.name}@${f.version} | ${copy.replace(/\|/g, '/')} |`);
  }
  out.push('');
  out.push('## Packages to note', '');
  for (const r of flagged) out.push(`- **${r.name}@${r.version}** (${r.id}). ${reviewOf(r.name) ?? 'Not reviewed.'}`);
  out.push('- **@openai/codex-sdk** drives the Codex CLI (`@openai/codex`, Apache-2.0), which npm installs with its platform binary.');
  if (counts['BlueOak-1.0.0']) out.push(`- ${counts['BlueOak-1.0.0']} packages are **BlueOak-1.0.0**, a permissive licence like MIT (common in the npm/isaacs ecosystem). Allowed.`);
  out.push('');
  out.push('## All production packages', '');
  out.push('| Package | Version | Licence | Source |', '|---|---|---|---|');
  for (const r of rows) out.push(`| ${r.name} | ${r.version} | ${r.id} | ${r.repo || ''} |`);
  out.push('');
  out.push('## Licence texts', '');
  out.push('Each distinct licence text once, with the packages it covers.', '');
  const byText = new Map();
  for (const r of rows) {
    const t = r.text || `(no licence file in the package; package.json says ${r.id})`;
    const k = t.replace(/\s+/g, ' ');
    if (!byText.has(k)) byText.set(k, { text: t, ids: new Set(), pkgs: [] });
    byText.get(k).ids.add(r.id);
    byText.get(k).pkgs.push(`${r.name}@${r.version}`);
  }
  for (const { text, ids, pkgs } of byText.values()) {
    out.push(`### ${[...ids].join(', ')}: ${pkgs.join(', ')}`, '', '```text', text.replace(/```/g, "'''"), '```', '');
  }
  fs.writeFileSync('THIRD_PARTY_NOTICES.md', out.join('\n'));
  console.log('\nWrote THIRD_PARTY_NOTICES.md');
}

process.exit(flagged.some((r) => !reviewOf(r.name)) ? 1 : 0);
